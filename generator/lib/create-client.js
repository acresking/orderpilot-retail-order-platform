function writeEnv(clientDir, opts) {
  const lines = [
    '# Generated by the OrderPilot generator — do not commit.',
    'NODE_ENV=production',
    'PORT=3000',
    'ORDERPILOT_HOST=0.0.0.0',
    `CODE_PEPPER=${randomHex(32)}`,
    '# DATA_ENCRYPTION_KEY is intentionally omitted — the server generates and persists a fresh',
    '# one here automatically on first boot, unique to this client.',
    '',
  ];
  fs.writeFileSync(path.join(clientDir, '.env'), lines.join('\n'), 'utf8');
}

function readPlatformVersion() {
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(PLATFORM_DIR, 'package.json'), 'utf8'));
    return pkg.version || '1.0.0';
  } catch (_) {
    return '1.0.0';
  }
}

async function createClient(opts) {
  fs.mkdirSync(CLIENTS_DIR, { recursive: true });
  const slug = uniqueFolderName(slugify(opts.companyName));
  const clientDir = path.join(CLIENTS_DIR, slug);

  copyDir(PLATFORM_DIR, clientDir);
  applyLogo(clientDir, opts.logo);
  seedData(clientDir, { ...opts, platformVersion: readPlatformVersion() });
  writeEnv(clientDir, opts);

  const log = [];
  const run = (cmd) => {
    log.push(`$ ${cmd}`);
    try {
      const out = execSync(cmd, { cwd: clientDir, stdio: 'pipe' }).toString();
      log.push(out.trim());
      return true;
    } catch (err) {
      log.push(`[ERROR] ${err.message}`);
      return false;
    }
  };

  const installOk = run('npm install --omit=dev');
  const buildOk = installOk && run('node scripts/build-web.js');

  return { slug, clientDir, installOk, buildOk, log };
}

