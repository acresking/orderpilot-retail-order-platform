function slugify(name) {
  const base = String(name || 'client').trim()
    .replace(/[^\p{L}\p{N}\s-]/gu, '')
    .replace(/\s+/g, '-')
    .toLowerCase();
  return base || 'client';
}

function uniqueFolderName(baseSlug) {
  let candidate = baseSlug;
  let i = 1;
  while (fs.existsSync(path.join(CLIENTS_DIR, candidate))) {
    i += 1;
    candidate = `${baseSlug}-${i}`;
  }
  return candidate;
}

function copyDir(src, dst) {
  if (!fs.existsSync(src)) return;
  const base = path.basename(src);
  if (IGNORE_NAMES.has(base)) return;
  const st = fs.statSync(src);
  if (st.isDirectory()) {
    fs.mkdirSync(dst, { recursive: true });
    for (const name of fs.readdirSync(src)) copyDir(path.join(src, name), path.join(dst, name));
  } else {
    fs.mkdirSync(path.dirname(dst), { recursive: true });
    fs.copyFileSync(src, dst);
  }
}

function writeJsonFile(filePath, value) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, JSON.stringify(value, null, 2), 'utf8');
}

// Wraps a raster logo (any format the browser can decode) as a minimal valid SVG so it can be
// dropped in as icon.svg without needing an image-resizing library — the SVG just embeds the
// original bytes as a data URI and stretches them to fill the viewBox.
function wrapAsSvg(buffer, mime) {
  const b64 = buffer.toString('base64');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512"><image href="data:${mime};base64,${b64}" width="512" height="512" preserveAspectRatio="xMidYMid slice"/></svg>`;
}

function applyLogo(clientDir, logo) {
  if (!logo || !logo.buffer) return;
  const publicDir = path.join(clientDir, 'public');
  fs.mkdirSync(publicDir, { recursive: true });
  fs.writeFileSync(path.join(publicDir, 'icon-512.png'), logo.buffer);
  fs.writeFileSync(path.join(publicDir, 'icon-192.png'), logo.buffer);
  fs.writeFileSync(path.join(publicDir, 'icon.svg'), wrapAsSvg(logo.buffer, logo.mime || 'image/png'));
}

